import fs from 'node:fs';

const articles = JSON.parse(fs.readFileSync(new URL('./collection-longform.json', import.meta.url), 'utf8'));
const expansions = JSON.parse(fs.readFileSync(new URL('./collection-expansions.json', import.meta.url), 'utf8'));
articles.forEach(article => article.chapters.forEach((chapter, index) => chapter.paragraphs.push(expansions[article.id][index])));
const publicArticles = articles.map(({additions, ...article}) => ({
  ...article,
  paragraphs: article.chapters.flatMap(chapter => chapter.paragraphs)
}));
fs.writeFileSync(new URL('./dist/collection-longform.js', import.meta.url),
  `// Generated by build-collections.mjs from collection-longform.json.\nwindow.CURTAIN_CONTENT.articles.push(...${JSON.stringify(publicArticles, null, 2)});\n`);
console.log(`Prepared ${publicArticles.length} independent collection articles.`);
